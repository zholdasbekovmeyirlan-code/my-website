'use strict';
// Builds the browser-only demo of Бәрі: the web apps plus the real server code running in the page.
// Usage: node demo/build.js [outDir]   (default: demo/dist)
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const out = path.resolve(process.argv[2] || path.join(__dirname, 'dist'));
const SERVER_MODULES = ['lib/http', 'lib/validate', 'lib/pricing', 'lib/orders', 'lib/auth', 'lib/sms', 'lib/db', 'lib/idempotency', 'lib/uploads', 'routes/api', 'seed'];

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'demo'), { recursive: true });

// 1. Server code as CommonJS module factories.
let bundle = '/* Generated by demo/build.js from server/. Do not edit. */\nwindow.__BARI_MODULES__ = {\n';
for (const id of SERVER_MODULES) {
  const src = fs.readFileSync(path.join(root, 'server', id + '.js'), 'utf8');
  bundle += `${JSON.stringify(id)}: function (require, module, exports) {\n${src}\n},\n`;
}
const seedData = fs.readFileSync(path.join(root, 'server', 'seed-data.json'), 'utf8');
bundle += `"seed-data.json": function (require, module) { module.exports = ${seedData.trim()}; },\n};\n`;
fs.writeFileSync(path.join(out, 'demo', 'server-bundle.js'), bundle);

// 2. Web apps. Links between apps point at the demo pages.
const copy = (rel, transform) => {
  const from = path.join(root, rel);
  const to = path.join(out, rel.replace(/^bari\//, ''));
  fs.mkdirSync(path.dirname(to), { recursive: true });
  if (transform) fs.writeFileSync(to, transform(fs.readFileSync(from, 'utf8')));
  else fs.copyFileSync(from, to);
};
const relink = (s) => s
  .replace(/href="\/pro"/g, 'href="pro.html"')
  .replace(/href="\/partner"/g, 'href="partner.html"')
  .replace(/href="\/admin"/g, 'href="admin.html"')
  .replace(/href="\/"/g, 'href="app.html"');
for (const f of fs.readdirSync(path.join(root, 'bari', 'js'))) copy('bari/js/' + f, relink);
copy('bari/css/style.css');
copy('bari/icons/icon.svg');
for (const f of fs.readdirSync(path.join(root, 'bari', 'img', 'art'))) copy('bari/img/art/' + f);
copy('bari/vendor/leaflet/leaflet.js');
copy('bari/vendor/leaflet/leaflet.css');
fs.copyFileSync(path.join(__dirname, 'backend.js'), path.join(out, 'demo', 'backend.js'));
fs.copyFileSync(path.join(__dirname, 'demo.css'), path.join(out, 'demo', 'demo.css'));
fs.copyFileSync(path.join(__dirname, 'vendor', 'sql-asm.js'), path.join(out, 'demo', 'sql-asm.js'));

// 3. Pages: each app page loads sql.js and the in-browser server first.
const DEMO_HEAD = '<link rel="stylesheet" href="demo/demo.css">\n';
const DEMO_SCRIPTS = '<script src="demo/sql-asm.js"></script>\n<script src="demo/server-bundle.js"></script>\n<script src="demo/backend.js"></script>\n';
const page = (src, role, title) => {
  let html = fs.readFileSync(path.join(root, 'bari', src), 'utf8');
  html = html.replace('<link rel="manifest" href="manifest.webmanifest">\n', '');
  html = html.replace(/<title>[^<]*<\/title>/, `<title>${title}</title>`);
  html = html.replace('</head>', DEMO_HEAD + '</head>');
  html = html.replace(/<body([^>]*)>/, (m, attrs) => `<body${attrs} data-role="${role}">`);
  html = html.replace('<script src="vendor/leaflet/leaflet.js"></script>', DEMO_SCRIPTS + '<script src="vendor/leaflet/leaflet.js"></script>');
  return html;
};
fs.writeFileSync(path.join(out, 'app.html'), page('index.html', 'app.html', 'Бәрі демо'));
fs.writeFileSync(path.join(out, 'pro.html'), page('pro.html', 'pro.html', 'Бәрі Pro демо'));
fs.writeFileSync(path.join(out, 'partner.html'), page('partner.html', 'partner.html', 'Бәрі Бизнес демо'));
fs.writeFileSync(path.join(out, 'admin.html'), page('admin.html', 'admin.html', 'Бәрі әкімшісі демо'));
// index.html = the client app, the page to open first.
fs.copyFileSync(path.join(out, 'app.html'), path.join(out, 'index.html'));

console.log('Demo built in', out);
