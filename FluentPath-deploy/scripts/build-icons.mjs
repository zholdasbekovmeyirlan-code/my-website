// Builds js/icons.js: an inline SVG sprite of the Lucide icons the site uses (ISC licence, https://lucide.dev).
//   npm pack lucide-static@0.460.0 && tar xzf lucide-static-0.460.0.tgz
//   node scripts/build-icons.mjs package/icons
// To add an icon: put its Lucide name in ICONS and run the script again.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ICONS = [
  // navigation
  "house", "map", "brain", "bot", "target", "book-open", "chart-line", "ellipsis", "menu", "user", "users",
  // skills and pages
  "puzzle", "headphones", "mic", "pen-line", "book-open-text", "message-circle", "list-checks",
  "drama", "graduation-cap", "clipboard-check", "trophy", "library",
  // stats
  "flame", "zap", "snowflake", "star", "medal", "badge-check",
  // actions and controls
  "volume-2", "volume-x", "play", "pause", "square", "rotate-ccw", "refresh-cw", "x", "check",
  "arrow-left", "arrow-right", "chevron-left", "plus", "lock",
  "settings", "download", "upload", "smartphone", "timer", "sun", "moon", "music", "snail",
  "link", "trash-2", "key-round", "cloud", "bell", "pencil", "external-link",
  // feedback
  "sparkles", "party-popper", "lightbulb", "triangle-alert", "circle-help", "circle-check",
  // illustrations
  "sprout", "compass", "rocket", "footprints", "book-check", "gem", "calendar-check", "newspaper", "layers",
  "coffee", "plane", "shopping-bag", "briefcase", "stethoscope", "gift", "lightbulb", "map-pin", "presentation",
  "backpack", "inbox", "pin", "clipboard-list", "book", "flag", "heart",
];

const dir = process.argv[2] || "package/icons";
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const symbols = [...new Set(ICONS)].map((name) => {
  const svg = readFileSync(join(dir, `${name}.svg`), "utf8");
  const inner = svg
    .slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"))
    .replace(/\s*\n\s*/g, "")
    .replace(/\s+\/>/g, "/>");
  return `<symbol id="i-${name}" viewBox="0 0 24 24">${inner}</symbol>`;
});

const out = `/* FluentPath — icon sprite (Lucide icons, ISC licence, https://lucide.dev). Generated by scripts/build-icons.mjs. */
(() => {
  const SPRITE = ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${symbols.join("")}</svg>`)};
  // <use href="#i-…"> finds symbols anywhere in the document, so the sprite works even before <body> exists.
  (document.body || document.documentElement).insertAdjacentHTML("afterbegin", SPRITE);
  // ic("flame") → <svg class="ic">…</svg>; extra classes size or colour it.
  window.FP_IC = (name, cls = "") =>
    \`<svg class="ic\${cls ? " " + cls : ""}" aria-hidden="true" focusable="false"><use href="#i-\${name}"/></svg>\`;
})();
`;
writeFileSync(join(ROOT, "js", "icons.js"), out);
console.log(`${symbols.length} icons → js/icons.js (${out.length} bytes)`);
