// Records every fixed English text on the site (words, examples, phrases, listening tracks, story lines) with
// natural neural voices, so learners hear the same pleasant voice on every phone.
//
//   python3 -m venv .tts && .tts/bin/pip install kokoro-onnx soundfile
//   curl -LO https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/kokoro-v1.0.onnx
//   curl -LO https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/voices-v1.0.bin
//   PYTHON=.tts/bin/python node scripts/build-audio.mjs
//
// Needs ffmpeg. Only missing clips are recorded, so re-run it after adding content. Writes audio/ and js/audio-index.js.
import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ctx = { window: {} };
vm.createContext(ctx);
for (const f of ["data.js", "course-data.js", "content-extra.js", "voice.js"]) {
  vm.runInContext(readFileSync(join(ROOT, "js", f), "utf8"), ctx, { filename: f });
}
const D = ctx.window.FP_DATA;
const V = ctx.window.FP_VOICE;

const jobs = new Map();
const add = (voice, text) => {
  const t = V.norm(text);
  if (!t || !/[a-z]/i.test(t)) return;
  const id = V.clipId(voice, t);
  if (!jobs.has(`${voice}/${id}`)) jobs.set(`${voice}/${id}`, { voice, kokoro: V.VOICES[voice].kokoro, text: t, id });
};
const sentences = (text) => String(text).split(/(?<=[.!?])\s+/).map((s) => s.trim()).filter(Boolean);

D.vocab.forEach((w) => {
  add("nar", w.en);
  add("nar", w.example);
});
(D.wordOfDayPool || []).forEach((w) => add("nar", w.word));
(D.phrases || []).forEach((p) => add("nar", p.en));
D.lessons.forEach((l) => (l.drills || []).forEach((d) => d.en && add("nar", d.en)));
(D.listening || []).forEach((tr, i) => sentences(tr.text).forEach((s) => add(V.trackVoice(i), s)));
(D.stories || []).forEach((st) => {
  const cast = V.storyVoices(st);
  st.lines.forEach(([who, en]) => add(who ? cast[who] || "nar" : "nar", en));
});

const list = [...jobs.values()];
const missing = list.filter((j) => !existsSync(join(ROOT, "audio", j.voice, `${j.id}.mp3`)));
console.log(`${list.length} clips, ${missing.length} to record`);
if (missing.length) {
  const file = join(tmpdir(), `fp-audio-jobs-${process.pid}.json`);
  writeFileSync(file, JSON.stringify(missing));
  const py = process.env.PYTHON || "python3";
  const r = spawnSync(py, [join(ROOT, "scripts", "tts-kokoro.py"), file, join(ROOT, "audio")], { stdio: "inherit" });
  if (r.status !== 0) process.exit(r.status || 1);
}

// Index of recorded clips, so the page knows what exists without trying URLs.
const index = {};
const stale = [];
Object.keys(V.VOICES).forEach((voice) => {
  const dir = join(ROOT, "audio", voice);
  if (!existsSync(dir)) return;
  const want = new Set(list.filter((j) => j.voice === voice).map((j) => j.id));
  const have = readdirSync(dir).filter((f) => f.endsWith(".mp3")).map((f) => f.slice(0, -4));
  index[voice] = have.filter((id) => want.has(id)).sort().join(" ");
  have.filter((id) => !want.has(id)).forEach((id) => stale.push(`audio/${voice}/${id}.mp3`));
});
mkdirSync(join(ROOT, "js"), { recursive: true });
writeFileSync(
  join(ROOT, "js", "audio-index.js"),
  `/* Generated by scripts/build-audio.mjs — recorded voice clips (see js/voice.js). */\nwindow.FP_AUDIO = ${JSON.stringify(index, null, 0)};\n`
);
console.log(`index written: ${Object.values(index).reduce((n, s) => n + (s ? s.split(" ").length : 0), 0)} clips`);
if (stale.length) console.log(`${stale.length} clips no longer used (safe to delete):\n${stale.join("\n")}`);
